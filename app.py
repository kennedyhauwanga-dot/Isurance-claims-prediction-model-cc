import warnings
warnings.filterwarnings("ignore")


numeric_cols     = X.select_dtypes(include=np.number).columns.tolist()
categorical_cols = X.select_dtypes(include=["object", "category", "bool"]).columns.tolist()

print(f"Numeric features: {len(numeric_cols)}")
print(f"Categorical features: {len(categorical_cols)}")

numeric_pipe = Pipeline([("imputer", SimpleImputer(strategy="median"))])
try:
    ohe = OneHotEncoder(handle_unknown="ignore", sparse_output=False)
except TypeError:
    # Compatibility with older scikit-learn versions
    ohe = OneHotEncoder(handle_unknown="ignore", sparse=False)

categorical_pipe = Pipeline([
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("encoder", ohe),
])
preprocessor = ColumnTransformer(
    transformers=[("num", numeric_pipe, numeric_cols),
                  ("cat", categorical_pipe, categorical_cols)],
    remainder="drop"
)

# threshold optimizer (maximise F1)
def best_f1_threshold(y_true, y_prob, lo=0.05, hi=0.95, step=0.01):
    grid = np.arange(lo, hi + 1e-9, step)
    f1s  = [f1_score(y_true, (y_prob >= t).astype(int), zero_division=0) for t in grid]
    k    = int(np.argmax(f1s))
    return float(grid[k]), float(f1s[k])

results   = {}
models    = {}
thresholds = {}   # <-- now defined! needed by later cells

for label in ORDER:
    print("\n" + "=" * 70)
    print(f"TRAINING {label} MODEL")
    print("=" * 70)

    target_col = HORIZONS[label]
    y = df[target_col].astype(int)
    print(f"Class distribution for {label}:")
    print(y.value_counts(normalize=True))

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.20, random_state=42, stratify=y
    )

    pos = (y_train == 1).sum()
    neg = (y_train == 0).sum()
    spw = neg / max(pos, 1)
    print(f"Calculated scale_pos_weight: {spw:.2f}")

    base_model = xgb.XGBClassifier(
        objective="binary:logistic",
        eval_metric="aucpr",           # <-- changed: aligned with the search metric
        tree_method="hist",
        random_state=42,
        n_jobs=-1,
    )

    pipeline = Pipeline([("preprocess", preprocessor), ("model", base_model)])

    # richer / stronger search space
    param_dist = {
        "model__n_estimators":     [300, 500, 800, 1200],
        "model__learning_rate":    [0.01, 0.03, 0.05, 0.1],
        "model__max_depth":        [3, 4, 5, 6, 8],
        "model__min_child_weight": [1, 2, 4, 8],
        "model__subsample":        [0.6, 0.8, 1.0],
        "model__colsample_bytree": [0.6, 0.8, 1.0],
        "model__gamma":            [0, 0.1, 0.3, 0.5],
        "model__reg_alpha":        [0, 0.1, 0.5, 1.0],
        "model__reg_lambda":       [1, 3, 5, 10],
        "model__scale_pos_weight": [1.0, spw * 0.5, spw, spw * 1.5],
    }

    search = RandomizedSearchCV(
        estimator=pipeline,
        param_distributions=param_dist,
        n_iter=60,                  # <-- more iterations
        cv=5,                       # <-- 5-fold (was 3)
        scoring="average_precision",
        n_jobs=-1,
        random_state=42,
        verbose=0,
        refit=True,
    )
    search.fit(X_train, y_train)

    model = search.best_estimator_
    models[label] = model

    print(f"\nBest CV AUC-PR: {search.best_score_:.4f}")
    print("Best parameters:")
    for k, v in search.best_params_.items():
        print(f"  {k}: {v}")

    # TEST EVALUATION
    y_prob = model.predict_proba(X_test)[:, 1]

    # default 0.5 prediction
    y_pred_50 = (y_prob >= 0.5).astype(int)

    # tuned-threshold prediction
    t_opt, f1_opt = best_f1_threshold(y_test, y_prob)
    thresholds[label] = t_opt
    y_pred_best = (y_prob >= t_opt).astype(int)

    results[label] = {
        "y_test":      y_test,
        "y_prob":      y_prob,
        "y_pred_50":   y_pred_50,
        "y_pred_best": y_pred_best,         # <-- now defined
        "threshold":   t_opt,
        "auc_roc":     roc_auc_score(y_test, y_prob),
        "auc_pr":      average_precision_score(y_test, y_prob),
        "brier":       brier_score_loss(y_test, y_prob),   # <-- now defined
        "accuracy":    accuracy_score(y_test, y_pred_best),
        "accuracy_50": accuracy_score(y_test, y_pred_50),
        "f1_best":     f1_opt,
    }

    print("\nTEST PERFORMANCE  (threshold = {:.2f})".format(t_opt))
    print(f"Accuracy @0.50 : {results[label]['accuracy_50']:.4f}")
    print(f"Accuracy @tuned: {results[label]['accuracy']:.4f}")
    print(f"AUC-ROC : {results[label]['auc_roc']:.4f}")
    print(f"AUC-PR  : {results[label]['auc_pr']:.4f}")
    print(f"Brier   : {results[label]['brier']:.4f}")
    print("\nClassification Report (tuned threshold):")
    print(classification_report(y_test, y_pred_best,
                                target_names=["No claim", "Claim"],
                                zero_division=0))

